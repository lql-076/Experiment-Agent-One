"""隐私第一道关：写死的关键词名单，宁严勿松。任何一个词出现，这件事就只在本地处理。
第二道关在 router.py：决策脑也会判断一次。两道关任何一道说是隐私，就按隐私处理。
你可以在 设置 › 分流旋钮 › 额外隐私关键词 里加词（逗号分隔）。
"""
import re

from . import settings

WORDS = [
    # 健康
    "药", "医院", "医生", "门诊", "挂号", "病", "症", "疼", "痛", "失眠", "睡不着", "抑郁", "焦虑", "情绪", "心理",
    "体检", "报告单", "化验", "处方", "血压", "血糖", "脱发", "体重", "身体", "健康", "难受", "头晕", "发烧", "感冒",
    "咳嗽", "过敏", "复诊", "住院", "手术", "治疗", "诊断", "精神",
    # 账号与钱
    "密码", "验证码", "身份证", "银行卡", "卡号", "工资", "存款", "余额", "欠款", "贷款",
    # 明说的
    "隐私", "私密", "别告诉", "不要外传", "保密",
]


def _all_words():
    extra = [w.strip() for w in re.split(r"[,，、\s]+", settings.S.get("privWords", "") or "") if w.strip()]
    return WORDS + extra


def check(text: str):
    """返回 (是否隐私, 命中的词)。"""
    t = text or ""
    for w in _all_words():
        if w in t:
            return True, w
    return False, ""
